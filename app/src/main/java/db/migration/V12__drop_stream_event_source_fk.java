package db.migration;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;

/**
 * Axiom 3.x incremental migration 12.
 *
 * <p>Drops the {@code stream_event.event_source_id -> event_source.id} foreign key so that internally
 * generated stream events (e.g. {@code system}, {@code sdk}) need no configured event source row.</p>
 *
 * <p>Implemented in Java because the constraint name is generated by the database (e.g. {@code CONSTRAINT_7F18}
 * in H2), so it is looked up in {@code INFORMATION_SCHEMA} rather than hard-coded.</p>
 */
public class V12__drop_stream_event_source_fk extends BaseJavaMigration {

    private static final String FIND_FK = "select tc.constraint_schema, tc.constraint_name"
            + " from information_schema.table_constraints tc"
            + " join information_schema.key_column_usage kcu"
            + " on kcu.constraint_schema = tc.constraint_schema and kcu.constraint_name = tc.constraint_name"
            + " where tc.constraint_type = 'FOREIGN KEY'"
            + " and upper(tc.table_name) = 'STREAM_EVENT'"
            + " and upper(kcu.column_name) = 'EVENT_SOURCE_ID'"
            + " and tc.table_schema = current_schema";

    /**
     * Finds and drops every foreign key on {@code stream_event.event_source_id}.
     *
     * @param context the Flyway migration context
     * @throws SQLException if the lookup or the drop fails
     */
    @Override
    public void migrate(Context context) throws SQLException {
        Connection connection = context.getConnection();
        List<String> constraints = new ArrayList<>();
        try (PreparedStatement find = connection.prepareStatement(FIND_FK);
                ResultSet rs = find.executeQuery()) {
            while (rs.next()) {
                constraints.add(quote(rs.getString(1)) + "." + quote(rs.getString(2)));
            }
        }
        try (Statement drop = connection.createStatement()) {
            for (String constraint : constraints) {
                drop.execute("alter table stream_event drop constraint " + constraint);
            }
        }
    }

    /**
     * Quotes an SQL identifier.
     *
     * @param identifier the identifier
     * @return the quoted identifier
     */
    private static String quote(String identifier) {
        return "\"" + identifier.replace("\"", "\"\"") + "\"";
    }
}
