import {
    DescriptionList,
    DescriptionListDescription,
    DescriptionListGroup,
    DescriptionListTerm,
    Label,
    Modal,
    ModalBody,
    ModalHeader,
    Tab,
    TabTitleText,
    Tabs,
} from "@patternfly/react-core";
import { Table, Tbody, Td, Th, Thead, Tr } from "@patternfly/react-table";
import { CodeEditor, Language } from "@patternfly/react-code-editor";
import ExclamationCircleIcon from "@patternfly/react-icons/dist/esm/icons/exclamation-circle-icon";
import { useState } from "react";
import { useEffectiveTheme } from "../../hooks/useTheme";
import { ValidationProblemsTab } from "./ValidationProblemsTab";
import "./ActionTypeDetailModal.css";

interface SubscriptionDetailModalProps {
    isOpen: boolean;
    onClose: () => void;
    name: string;
    content: Record<string, unknown>;
    errors?: string[];
}

interface RoutingRuleContent {
    type?: string;
    workflowDefinitionId?: number;
    workflowDefinitionName?: string;
}

/**
 * Describes a routing rule's target workflow.
 *
 * @param rule the routing rule
 * @returns the workflow name, "#id", or a dash for rules without a target
 */
function routingTarget(rule: RoutingRuleContent): string {
    if (rule.workflowDefinitionName) {
        return rule.workflowDefinitionName;
    }
    if (rule.workflowDefinitionId !== undefined && rule.workflowDefinitionId !== null) {
        return `#${rule.workflowDefinitionId}`;
    }
    return rule.type === "workflow-dispatch" ? "Waiting runs on the matching subject" : "—";
}

/** Preview of a subscription generated by the Configuration Assistant: details, routing, source and problems. */
export function SubscriptionDetailModal({ isOpen, onClose, name, content, errors }: SubscriptionDetailModalProps) {
    const effectiveTheme = useEffectiveTheme();
    const [activeTab, setActiveTab] = useState(0);

    const description = (content.description as string) || "";
    const enabled = (content.enabled as boolean | undefined) ?? false;
    const filterExpression = (content.filterExpression as string) || "";
    const routing = Array.isArray(content.routing) ? (content.routing as RoutingRuleContent[]) : [];
    const labels = (content.labels as string[]) || [];

    return (
        <Modal
            isOpen={isOpen}
            onClose={onClose}
            variant="large"
            aria-label={`Subscription: ${name}`}
            style={{ height: "80vh" }}
        >
            <ModalHeader title={`Subscription: ${name}`} />
            <ModalBody className="assistant-tabbed-modal-body">
                <Tabs activeKey={activeTab} onSelect={(_e, key) => setActiveTab(key as number)}>
                    <Tab eventKey={0} title={<TabTitleText>Details</TabTitleText>}>
                        <div style={{ paddingTop: 16 }}>
                            <DescriptionList isHorizontal isCompact>
                                <DescriptionListGroup>
                                    <DescriptionListTerm>Name</DescriptionListTerm>
                                    <DescriptionListDescription>{name}</DescriptionListDescription>
                                </DescriptionListGroup>
                                <DescriptionListGroup>
                                    <DescriptionListTerm>Description</DescriptionListTerm>
                                    <DescriptionListDescription>{description || "—"}</DescriptionListDescription>
                                </DescriptionListGroup>
                                <DescriptionListGroup>
                                    <DescriptionListTerm>Enabled</DescriptionListTerm>
                                    <DescriptionListDescription>{enabled ? "Yes" : "No"}</DescriptionListDescription>
                                </DescriptionListGroup>
                                <DescriptionListGroup>
                                    <DescriptionListTerm>Filter</DescriptionListTerm>
                                    <DescriptionListDescription>
                                        {filterExpression ? <code>{filterExpression}</code> : "All events"}
                                    </DescriptionListDescription>
                                </DescriptionListGroup>
                                {labels.length > 0 && (
                                    <DescriptionListGroup>
                                        <DescriptionListTerm>Labels</DescriptionListTerm>
                                        <DescriptionListDescription>
                                            <div style={{ display: "flex", flexWrap: "wrap", gap: 4 }}>
                                                {labels.map((l) => (
                                                    <Label key={l} isCompact color="grey">{l}</Label>
                                                ))}
                                            </div>
                                        </DescriptionListDescription>
                                    </DescriptionListGroup>
                                )}
                            </DescriptionList>
                        </div>
                    </Tab>
                    <Tab eventKey={1} title={<TabTitleText>Routing</TabTitleText>}>
                        <div style={{ paddingTop: 16 }}>
                            {routing.length === 0 ? (
                                <div>No routing rules: matching events are recorded but not routed.</div>
                            ) : (
                                <Table aria-label="Routing rules" variant="compact">
                                    <Thead>
                                        <Tr>
                                            <Th>Type</Th>
                                            <Th>Workflow</Th>
                                        </Tr>
                                    </Thead>
                                    <Tbody>
                                        {routing.map((rule, i) => (
                                            <Tr key={i}>
                                                <Td dataLabel="Type">{rule.type || "—"}</Td>
                                                <Td dataLabel="Workflow">{routingTarget(rule)}</Td>
                                            </Tr>
                                        ))}
                                    </Tbody>
                                </Table>
                            )}
                        </div>
                    </Tab>
                    <Tab eventKey={2} title={<TabTitleText>Source</TabTitleText>}>
                        <div style={{ paddingTop: 16, flex: "1 1 0", minHeight: 0 }}>
                            <CodeEditor
                                code={JSON.stringify(content, null, 2)}
                                language={Language.json}
                                isDarkTheme={effectiveTheme === "dark"}
                                height="100%"
                                isReadOnly
                                isLineNumbersVisible
                            />
                        </div>
                    </Tab>
                    {(errors?.length ?? 0) > 0 && (
                        <Tab eventKey={3} title={
                            <TabTitleText>
                                <ExclamationCircleIcon className="axiom-icon-danger" style={{ marginRight: 6 }} />
                                Problems ({errors!.length})
                            </TabTitleText>
                        }>
                            <ValidationProblemsTab errors={errors} />
                        </Tab>
                    )}
                </Tabs>
            </ModalBody>
        </Modal>
    );
}
