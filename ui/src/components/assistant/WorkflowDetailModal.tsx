import {
    Alert,
    DescriptionList,
    DescriptionListDescription,
    DescriptionListGroup,
    DescriptionListTerm,
    Modal,
    ModalBody,
    ModalHeader,
    Tab,
    TabTitleText,
    Tabs,
} from "@patternfly/react-core";
import { CodeEditor, Language } from "@patternfly/react-code-editor";
import ExclamationCircleIcon from "@patternfly/react-icons/dist/esm/icons/exclamation-circle-icon";
import { WorkflowEditor } from "@apitomy/flow-ui";
import type { Workflow } from "@apitomy/flow-ui";
import { useWorkflowEditorSpi } from "../../hooks/useWorkflowEditorSpi";
import { useMemo, useState } from "react";
import { useEffectiveTheme } from "../../hooks/useTheme";
import { ValidationProblemsTab } from "./ValidationProblemsTab";
import { FieldsTable } from "./FieldsTable";
import "./ActionTypeDetailModal.css";

interface WorkflowDetailModalProps {
    isOpen: boolean;
    onClose: () => void;
    name: string;
    content: Record<string, unknown>;
    errors?: string[];
}

interface StartInput {
    name?: string;
    type?: string;
    required?: boolean;
    description?: string;
}

/**
 * Extracts the workflow graph from an assistant workflow file. The file's {@code content} may be an object
 * or a JSON string.
 *
 * @param content the parsed workflow file
 * @returns the graph, or an error message when it cannot be read
 */
export function parseWorkflowContent(content: Record<string, unknown>): { workflow?: Workflow; error?: string } {
    let graph: unknown = content.content;
    if (typeof graph === "string") {
        try {
            graph = JSON.parse(graph);
        } catch (e) {
            return { error: `The workflow content is not valid JSON: ${(e as Error).message}` };
        }
    }
    if (!graph || typeof graph !== "object") {
        return { error: "The workflow file has no content object." };
    }
    const wf = graph as Partial<Workflow>;
    if (!Array.isArray(wf.nodes) || !Array.isArray(wf.edges)) {
        return { error: "The workflow content must contain nodes and edges arrays." };
    }
    return { workflow: wf as Workflow };
}

/** Preview of a workflow generated by the Configuration Assistant: diagram, details, source and problems. */
export function WorkflowDetailModal({ isOpen, onClose, name, content, errors }: WorkflowDetailModalProps) {
    const effectiveTheme = useEffectiveTheme();
    const [activeTab, setActiveTab] = useState(0);
    const { workflow, error } = useMemo(() => parseWorkflowContent(content), [content]);
    const spi = useWorkflowEditorSpi();

    const description = (content.description as string) || "";
    const startNode = workflow?.nodes.find((n) => n.type === "start");
    const startInputs = ((startNode?.config as { inputs?: StartInput[] } | undefined)?.inputs) ?? [];

    return (
        <Modal
            isOpen={isOpen}
            onClose={onClose}
            variant="large"
            aria-label={`Workflow: ${name}`}
            style={{ height: "85vh" }}
        >
            <ModalHeader title={`Workflow: ${name}`} />
            <ModalBody className="assistant-tabbed-modal-body">
                <Tabs activeKey={activeTab} onSelect={(_e, key) => setActiveTab(key as number)}>
                    <Tab eventKey={0} title={<TabTitleText>Diagram</TabTitleText>}>
                        <div style={{ paddingTop: 16, height: "60vh" }}>
                            {workflow ? (
                                <WorkflowEditor
                                    workflow={workflow}
                                    readOnly
                                    spi={spi}
                                    theme={effectiveTheme === "dark" ? "dark" : "light"}
                                />
                            ) : (
                                <Alert variant="danger" isInline title="Cannot display this workflow">
                                    {error}
                                </Alert>
                            )}
                        </div>
                    </Tab>
                    <Tab eventKey={1} title={<TabTitleText>Details</TabTitleText>}>
                        <div style={{ paddingTop: 16 }}>
                            <DescriptionList isHorizontal isCompact>
                                <DescriptionListGroup>
                                    <DescriptionListTerm>Name</DescriptionListTerm>
                                    <DescriptionListDescription>{name}</DescriptionListDescription>
                                </DescriptionListGroup>
                                <DescriptionListGroup>
                                    <DescriptionListTerm>Description</DescriptionListTerm>
                                    <DescriptionListDescription>{description || "—"}</DescriptionListDescription>
                                </DescriptionListGroup>
                                <DescriptionListGroup>
                                    <DescriptionListTerm>Nodes / edges</DescriptionListTerm>
                                    <DescriptionListDescription>
                                        {workflow ? `${workflow.nodes.length} / ${workflow.edges.length}` : "—"}
                                    </DescriptionListDescription>
                                </DescriptionListGroup>
                            </DescriptionList>
                        </div>
                    </Tab>
                    {startInputs.length > 0 && (
                        <Tab eventKey={4} title={<TabTitleText>Inputs ({startInputs.length})</TabTitleText>}>
                            <div style={{ paddingTop: 16 }}>
                                <FieldsTable fields={startInputs.map((input) => ({
                                    name: input.name ?? "",
                                    type: input.type,
                                    required: input.required,
                                    description: input.description,
                                }))} />
                            </div>
                        </Tab>
                    )}
                    <Tab eventKey={2} title={<TabTitleText>Source</TabTitleText>}>
                        <div style={{ paddingTop: 16, flex: "1 1 0", minHeight: 0 }}>
                            <CodeEditor
                                code={JSON.stringify(content, null, 2)}
                                language={Language.json}
                                isDarkTheme={effectiveTheme === "dark"}
                                height="100%"
                                isReadOnly
                                isLineNumbersVisible
                            />
                        </div>
                    </Tab>
                    {(errors?.length ?? 0) > 0 && (
                        <Tab eventKey={3} title={
                            <TabTitleText>
                                <ExclamationCircleIcon className="axiom-icon-danger" style={{ marginRight: 6 }} />
                                Problems ({errors!.length})
                            </TabTitleText>
                        }>
                            <ValidationProblemsTab errors={errors} />
                        </Tab>
                    )}
                </Tabs>
            </ModalBody>
        </Modal>
    );
}
